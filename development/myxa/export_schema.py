"""Generate the initial MYXA parameter contract and embedded factory data.
Run with desktop/live/.venv/bin/python development/myxa/export_schema.py.
IDs are frozen in schema.json after creation; changes require explicit migration.
"""
import json
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'desktop/live'))
from model import MODEL_D_PARAMETERS, read_patch
HERE=Path(__file__).parent
specs=[{'id':i+1,'key':p.name,'minimum':p.minimum,'maximum':p.maximum,'discrete':bool(p.choices)} for i,p in enumerate(MODEL_D_PARAMETERS)]
for key,low,high in [('pan',-1,1),('output_gain_db',-24,24),('eq_bass_db',-12,12),('eq_mid_db',-12,12),('eq_treble_db',-12,12),('reverb_mix',0,1),('reverb_decay_s',.15,2.5)]:
    specs.append(dict(id=len(specs)+1,key=key,minimum=low,maximum=high,discrete=False))
schema={'version':1,'parameters':specs,'engine_ids':{'modeld':3,'modeld18':4}}
path=HERE/'schema.json'
if path.exists() and json.loads(path.read_text())!=schema:
    raise SystemExit('Schema changed: review IDs and define a migration before regenerating')
patches=[]
for filename in ('UK-Res-Bass','BOSS-03','Moog-Res'):
    p=read_patch(ROOT/'presets/user'/f'{filename}.json')
    eq=p['eq']
    if eq['enabled'] and (eq['low_hz'],eq['mid_hz'],eq['mid_q'],eq['high_hz'])!=(100,700,.7,2500):
        raise SystemExit('Factory EQ requires unsupported custom tuning; do not silently convert')
    values={**p['parameters'],'pan':0,'output_gain_db':p.get('output_gain_db',0),
        'eq_bass_db':eq['low_db'] if eq['enabled'] else 0,'eq_mid_db':eq['mid_db'] if eq['enabled'] else 0,
        'eq_treble_db':eq['high_db'] if eq['enabled'] else 0,
        'reverb_mix':p['reverb']['mix'],'reverb_decay_s':p['reverb']['decay']}
    patches.append({'name':p['name'],'engine':schema['engine_ids'][p['architecture']], 'values':[values[s['key']] for s in specs]})
lines=['/* Generated by export_schema.py. Do not reorder IDs. */','#ifndef MYXA_PARAMETERS_H','#define MYXA_PARAMETERS_H', '#include <stdint.h>','enum myxa_parameter_id {']
lines += [f"    MYXA_{s['key'].upper()} = {s['id']}," for s in specs]
lines+=['};',f'#define MYXA_PARAMETER_COUNT {len(specs)}',f'#define MYXA_SCHEMA_VERSION {schema["version"]}',
    'typedef struct { const char *name; uint16_t engine; float values[MYXA_PARAMETER_COUNT]; } myxa_factory_patch;',
    'static const myxa_factory_patch myxa_factory_patches[] = {']
for p in patches:
    floats=', '.join(format(float(v),'.9e')+'f' for v in p['values'])
    lines.append('    {'+json.dumps(p['name'])+', '+str(p['engine'])+', {'+floats+'}},')
lines+=['};','static const float myxa_minimum[MYXA_PARAMETER_COUNT] = {'+', '.join(format(float(s['minimum']),'.9e')+'f' for s in specs)+'};',
    'static const float myxa_maximum[MYXA_PARAMETER_COUNT] = {'+', '.join(format(float(s['maximum']),'.9e')+'f' for s in specs)+'};',
    'static const unsigned char myxa_discrete[MYXA_PARAMETER_COUNT] = {'+', '.join(str(int(s['discrete'])) for s in specs)+'};','#endif','']
path.write_text(json.dumps(schema,indent=2)+'\n')
(HERE/'parameters.h').write_text('\n'.join(lines))
print(f'Exported {len(specs)} parameters and {len(patches)} factory patches; float32 payload {4*len(specs)} bytes per patch.')
